'use strict';
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const assets = [];
function walk(dir) {
  for (const entry of fs.readdirSync(dir, {withFileTypes:true})) {
    const relative = path.posix.join(dir, entry.name);
    if (entry.isDirectory()) { if (entry.name === 'tools') walk(relative); else if (dir.startsWith('tools')) walk(relative); }
    else if (/\.(html|css|js|json|webmanifest|svg)$/.test(entry.name) && (dir.startsWith('tools') || /^(index\.html|home-next\.|manifest\.|pct-next-icon)/.test(entry.name))) assets.push('./'+relative);
  }
}
process.chdir(root);
walk('.');
assets.sort();
const output = '// Generated by node scripts/build-offline.cjs. Do not edit.\nself.PCT_OFFLINE_ASSETS = '+JSON.stringify(assets,null,2)+';\n';
const target = path.join(root, 'offline-assets.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target,'utf8') !== output) { console.error('Offline assets are stale. Run npm run build:offline.'); process.exitCode=1; }
} else fs.writeFileSync(target,output);
